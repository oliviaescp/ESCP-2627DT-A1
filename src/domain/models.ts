export type Scenario = "restaurant" | "consulting";
export type DateRange = { start: string; end: string };
export type DashboardFilters = Record<string, string | string[]>;
export type UserContext = {
  industry: string;
  sector: string;
  position: string;
  companyOrProject: string;
  goal: string;
  scenario: Scenario;
};
export type Assumption = {
  id: string;
  title: string;
  description: string;
  expectedOutcome: string;
  createdAt: string;
  period?: DateRange;
};
export type KpiDefinition = {
  id: string;
  name: string;
  description: string;
  category: "financial" | "operational" | "customer" | "team" | "project";
  requiredInputs: string[];
  formulaKey: string;
  unit: "number" | "currency" | "percentage" | "hours";
  direction: "higher-is-better" | "lower-is-better";
  target?: number;
  warningThreshold: number;
  criticalThreshold: number;
  period: "day" | "week" | "month";
  custom?: boolean;
};
export type DataSource = {
  id: string;
  name: string;
  type: "csv" | "xlsx" | "sample";
  isSample: boolean;
  rowCount: number;
  fieldNames: string[];
  rows: Record<string, unknown>[];
  period?: DateRange;
  uploadedAt: string;
  freshness: "current" | "outdated" | "unknown";
  status: "valid" | "needs-review" | "invalid";
  warnings: string[];
  sheets?: string[];
  selectedSheet?: string;
};
export type DataMapping = {
  id: string;
  sourceId: string;
  sourceField: string;
  kpiId: string;
  inputName: string;
  confidence: number;
  status: "suggested" | "confirmed" | "unresolved";
};
export type SourceReference = {
  sourceId: string;
  sourceName: string;
  field: string;
  inputName: string;
  period: DateRange;
  rowCount: number;
  sheet?: string;
};
export type KpiStatus = "on-track" | "watch" | "critical" | "unavailable";
export type KpiResult = {
  id: string;
  kpiId: string;
  name: string;
  unit: KpiDefinition["unit"];
  value?: number;
  target?: number;
  variance?: number;
  variancePercent?: number;
  trend: "up" | "down" | "stable" | "unknown";
  status: KpiStatus;
  period: DateRange;
  comparisonPeriod?: DateRange;
  previousValue?: number;
  comparisonChange?: number;
  sourceReferences: SourceReference[];
  qualityNotes: string[];
  formula: string;
  operands: Record<string, number>;
  series: { date: string; value: number }[];
};
export type Warning = {
  id: string;
  kpiId?: string;
  priority: "low" | "medium" | "high";
  title: string;
  explanation: string;
  changedValues: string[];
  impact?: string;
  ruleKey: string;
  sourceReferences: SourceReference[];
  caveats: string[];
  possibleNextStep?: string;
};
export type Draft = {
  context: UserContext;
  assumptions: Assumption[];
  definitions: KpiDefinition[];
  sources: DataSource[];
  mappings: DataMapping[];
  dateRange: DateRange;
  comparisonPeriod: DateRange;
  filters: DashboardFilters;
};
export type Dashboard = Draft & {
  id: string;
  name: string;
  kpiResults: KpiResult[];
  warnings: Warning[];
  createdAt: string;
  updatedAt: string;
  chartType: "line" | "bar";
};
