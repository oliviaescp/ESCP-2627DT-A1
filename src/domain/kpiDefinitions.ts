export function recommendKpis(scenario: Scenario): KpiDefinition[] {
  const ids =
    scenario === "restaurant"
      ? restaurant
      : [
          "consulting-revenue",
          "project-completion",
          "team-utilization",
          "client-satisfaction",
          "overdue-tasks",
        ];
  return ids.map((id) => ({
    ...KPI_DEFINITIONS.find((k) => k.id === id)!,
    requiredInputs: [
      ...KPI_DEFINITIONS.find((k) => k.id === id)!.requiredInputs,
    ],
  }));
}
